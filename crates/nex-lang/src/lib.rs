//! The NEX language: lexer, parser, semantic analysis, bytecode compiler,
//! bytecode verifier, virtual machine and build-artifact format.
//!
//! Pipeline: source → [`lexer`] → [`parser`] → [`sema`] → [`compiler`]
//! → [`verify`] → [`vm`].

pub mod artifact;
pub mod ast;
pub mod bytecode;
pub mod compiler;
pub mod diag;
pub mod lexer;
pub mod parser;
pub mod sema;
pub mod span;
pub mod types;
pub mod verify;
pub mod vm;

use bytecode::Module;
use diag::Diagnostic;
use span::{SourceFile, Span};

/// Version of this NEX implementation.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// Compile source text to a verified bytecode module, or return every
/// diagnostic found. Nothing is executed.
pub fn compile_source(src: &SourceFile) -> Result<Module, Vec<Diagnostic>> {
    let program = parser::parse(&src.text).map_err(|d| vec![d])?;
    let analysis = sema::analyze(&program)?;
    let module = compiler::compile(&program, &analysis, src);
    if let Err(e) = verify::verify(&module) {
        return Err(vec![Diagnostic::error(
            format!("internal compiler error: generated bytecode failed verification ({e})"),
            Span::default(),
        )
        .note(
            "this is a bug in nex; please report it with the program that triggered it",
        )]);
    }
    Ok(module)
}

/// Compile and run every app in `src`, writing output to `out`.
/// Convenience for tests and embedding.
pub fn run_source(
    src: &SourceFile,
    out: &mut dyn std::io::Write,
    limits: &vm::Limits,
) -> Result<(), RunError> {
    let module = compile_source(src).map_err(RunError::Compile)?;
    for &app in &module.apps {
        vm::run_app(&module, app, out, limits).map_err(RunError::Runtime)?;
    }
    Ok(())
}

#[derive(Debug)]
pub enum RunError {
    Compile(Vec<Diagnostic>),
    Runtime(vm::RuntimeError),
}
