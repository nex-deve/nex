/// Version of this NEX implementation.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// Diagnostics from a failed compilation, with every file that was read so
/// that each diagnostic can be shown against its own file (`span.file`).
#[derive(Debug)]
pub struct CompileError {
    pub diagnostics: Vec<Diagnostic>,
    pub files: Vec<SourceFile>,
}

impl CompileError {
    /// Render every diagnostic against the file it belongs to.
    pub fn render(&self) -> String {
        self.diagnostics
            .iter()
            .map(|d| match self.files.get(d.span.file as usize) {
                Some(src) => d.render(src),
                None => format!("error: {}\n", d.message),
            })
            .collect::<Vec<_>>()
            .join("\n")
    }
}

/// Compile `main` and every module it uses (looked up under `root` by
/// `loader`) into one verified bytecode module. Nothing is executed.
pub fn compile_project(
    main: SourceFile,
    root: &Path,
    loader: &mut dyn Loader,
) -> Result<(Module, Vec<SourceFile>), CompileError> {
    let project = project::load(main, root, loader)
        .map_err(|(diagnostics, files)| CompileError { diagnostics, files })?;
    let analysis = match sema::analyze_units(&project.units) {
        Ok(a) => a,
        Err(diagnostics) => {
            return Err(CompileError {
                diagnostics,
                files: project.files,
            })
        }
    };
    let module = compiler::compile(&project.units, &analysis, &project.files);
    if let Err(e) = verify::verify(&module) {
        return Err(CompileError {
            diagnostics: vec![Diagnostic::error(
                format!("internal compiler error: generated bytecode failed verification ({e})"),
                Span::default(),
            )
            .note("this is a bug in nex; please report it with the program that triggered it")],
            files: project.files,
        });
    }
    Ok((module, project.files))
}

/// Compile a single file. Any `use` is reported as an unresolved module.
pub fn compile_source(src: &SourceFile) -> Result<Module, Vec<Diagnostic>> {
    compile_project(src.clone(), Path::new(""), &mut NoLoader)
        .map(|(module, _)| module)
        .map_err(|e| e.diagnostics)
}

/// Compile and run every app in `src` against `host`. Returns the code
/// passed to `exit`, if the program called it.
pub fn run_source(
    src: &SourceFile,
    host: &mut vm::Host,
    limits: &vm::Limits,
) -> Result<Option<i32>, RunError> {
    let module = compile_source(src).map_err(RunError::Compile)?;
    for &app in &module.apps {
        if let Some(code) = vm::run_app(&module, app, host, limits).map_err(RunError::Runtime)? {
            return Ok(Some(code));
        }
    }
    Ok(None)
}

#[derive(Debug)]
pub enum RunError {
    Compile(Vec<Diagnostic>),
    Runtime(vm::RuntimeError),
}
